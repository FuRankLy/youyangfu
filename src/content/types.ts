// Shapes of everything in src/content. Components import data, never hardcode it.

export type Place = {
  name: string;
  chinese?: string;
  lat: number;
  lon: number;
  /** IANA time zone, e.g. "Pacific/Auckland". */
  tz: string;
  /** How the latitude is written on the page, e.g. "36.8°S". */
  latLabel: string;
};

export type ChapterMeta = {
  /** Anchor id on the home page. */
  id: string;
  /** Financial numeral shown beside the title. */
  numeral: string;
  title: string;
  /** One line under the title. */
  blurb: string;
};

export type NavItem = {
  label: string;
  href: string;
  /** Chapter ids that light this item up while they are on screen. */
  chapters?: string[];
};

/** The exchange the life chart trades on: China's main stock exchange, then New Zealand's. */
export type Market = "SSE" | "NZX";

/** How one exchange lists the life chart. */
export type Listing = {
  exchange: Market;
  exchangeName: string;
  /** The listed name: Chinese stocks go by their Chinese name, NZX ones by a ticker. */
  name: string;
  /** Language tag of `name`, when it isn't English. */
  nameLang?: string;
};

/** Where the owner lived. Periods run back to back with no gaps; the last one has no `to`. */
export type LifePeriod = {
  place: string;
  country: string;
  /** YYYY-MM */
  from: string;
  /** YYYY-MM, inclusive. Leave out for where the owner lives now. */
  to?: string;
  market: Market;
};

/**
 * Something that really happened. Only events the owner has stated go here:
 * the chart's movement between them is generated, so nothing is invented.
 */
export type LifeEvent = {
  id: string;
  title: string;
  detail?: string;
  /** YYYY-MM */
  from: string;
  /** YYYY-MM, inclusive, for things that lasted a while. */
  to?: string;
  /** Short label for the flag under the chart. Leave out for no flag. */
  flag?: string;
  /** How far the line steps up over the months that follow (log scale, about 0.03 to 0.15). Leave out for none. */
  lift?: number;
  /** A big change of scene: the line moves more for a few months, in no set direction. */
  shake?: boolean;
  /** A brief, verified stock market fact from the same month, anywhere in the world. */
  market?: string;
};

/** "seasonal" is for something that runs part of each year and is resting the rest of the time. */
export type ProjectStatus = "live" | "seasonal" | "shipped" | "in-progress" | "archived" | "deprecated";

export type ProjectSection = {
  heading: string;
  body: string[];
};

export type Project = {
  slug: string;
  title: string;
  year: number;
  role: string;
  stack: string[];
  status: ProjectStatus;
  summary: string;
  links: { label: string; href: string }[];
  /** Path under /public, e.g. "/work/site.png". */
  cover?: string;
  /** What the cover image shows, for people who can't see it. */
  coverAlt?: string;
  sections: ProjectSection[];
  /** True while this entry is sample content. */
  placeholder?: boolean;
};

/** One job or internship in the Experience list. */
export type ExperienceRole = {
  organisation: string;
  role: string;
  /** As written on the page, e.g. "Nov 2025 to Feb 2026". */
  dates: string;
  /** One or two sentences. The CV holds the rest. */
  summary: string;
  /** A short marker beside the dates, e.g. "Incoming". */
  note?: string;
};

export type ToolArea = "Languages" | "Frontend" | "Backend" | "Data" | "Tools";

export type Tool = {
  name: string;
  area: ToolArea;
  /** Year first used. Leave out until known; the plaque then shows no year. */
  since?: number;
};

export type GearSlot = "racket" | "strings" | "grip" | "shoes" | "bag";

export type Gear = {
  slot: GearSlot;
  /** What it is: "Racket". */
  label: string;
  /** Make and model, when known: "Victor Thruster Ryuga". */
  name?: string;
  /** One short line about it. */
  detail?: string;
};

export type Game = {
  title: string;
  hours?: number;
  rank?: string;
  main?: string;
};

export type Fact = {
  /** A playing card, e.g. "K♠". */
  card: string;
  text: string;
};

export type RoomId = "court" | "table" | "arcade";

/** One of the three rooms in Off the clock. */
export type Room = {
  id: RoomId;
  title: string;
  chinese: string;
  /** A quiet line about what arrives in a later phase. */
  note?: string;
};

/** Land sampled onto a lattice for the square map. Generated by scripts/build-land-grid.mjs. */
export type LandGrid = {
  /** Frame edges in degrees. `east` runs past 180 when the frame crosses the antimeridian. */
  west: number;
  east: number;
  north: number;
  south: number;
  cols: number;
  rows: number;
  /** One string per row, north to south. "#" is land, "." is sea. */
  cells: string[];
};

/** Copy for the "Two homes" chapter. */
export type HomesContent = {
  /** Place, then what and when, in order: born, grew up, live now. */
  facts: { label: string; when: string }[];
  split: {
    /** Names read out for each part of the bar. */
    hometown: string;
    newZealand: string;
    /** "Zhengzhou, 10.3 years" */
    years: (count: string) => string;
    /** "New Zealand, 10.3 years and counting" */
    yearsCounting: (count: string) => string;
  };
  percentCaption: string;
  /** Followed by the crossover date, e.g. "14 November 2026". */
  crossover: { before: string; after: string };
  /** First-person paragraph about growing up between the two places. */
  story: string;
  /** True while `story` is sample copy. */
  placeholder: boolean;
  map: {
    /** What the map shows, for people who can't see it. */
    description: string;
    /** Added to the description once the time difference is known. */
    clockSentence: (hours: number) => string;
    /** Added to the description while the map is flipped. */
    flippedSentence: string;
    equator: string;
    /** Word before the time difference, as in "clock +5 h". */
    clock: string;
    flip: {
      button: string;
      /** One line shown while the map is flipped. */
      note: string;
    };
  };
};

/** A Texas Hold'em hand: two hole cards, then the board street by street. Cards are written like "7♦". */
export type Hand = {
  hole: [string, string];
  holeNote: string;
  /** Flop, turn, river. A street with no cards is not dealt yet and stays face down. */
  streets: { name: string; cards: string[]; note: string }[];
};
